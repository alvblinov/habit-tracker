/** Персонаж по id; неизвестный id → персонаж по умолчанию (кот). */
export function getCharacter(id) {
  return CHARACTERS.find((c) => c.id === id) ?? CHARACTERS.find((c) => c.id === DEFAULT_CHARACTER);
}

/** Имя помощника: trim, 1–20 символов. Иначе null (не сохранять). */
export function normalizeCompanionName(raw) {
  if (typeof raw !== 'string') return null;
  const name = raw.trim();
  if (name.length < 1 || name.length > MAX_NAME) return null;
  return name;
}

/** Настройки по умолчанию: Мурзик, включён, знакомство не пройдено. */
export function defaultCompanionSettings() {
  const cat = getCharacter(DEFAULT_CHARACTER);
  return {
    character: cat.id,
    name: cat.defaultName,
    enabled: true,
    introduced: false,
    tourOffered: false,
    lastTipDate: null,
  };
}

/**
 * Настройки из сохранённого значения (объект или JSON-строка).
 * Битое или отсутствующее → по умолчанию; неизвестный персонаж → кот;
 * неподходящее имя → имя персонажа по умолчанию; tourOffered — только true,
 * иначе false; lastTipDate — только существующая дата 'YYYY-MM-DD', иначе null.
 */
export function normalizeCompanionSettings(raw) {
  let data = raw;
  if (typeof data === 'string') {
    try {
      data = JSON.parse(data);
    } catch {
      return defaultCompanionSettings();
    }
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) return defaultCompanionSettings();
  const character = CHARACTERS.some((c) => c.id === data.character) ? data.character : DEFAULT_CHARACTER;
  return {
    character,
    name: normalizeCompanionName(data.name) ?? getCharacter(character).defaultName,
    enabled: data.enabled !== false,
    introduced: data.introduced === true,
    // Экскурсию предлагали после знакомства (предлагается один раз).
    tourOffered: data.tourOffered === true,
    // Локальная дата последнего совета дня 'YYYY-MM-DD' или null.
    lastTipDate: isDateKey(data.lastTipDate) ? data.lastTipDate : null,
  };
}

/** Относительный путь к картинке персонажа: анимированный WebP или статичный SVG. */
export function companionImage(id, { animated = false } = {}) {
  return `${COMPANION_DIR}${getCharacter(id).code}.${animated ? 'webp' : 'svg'}`;
}

/** Часть суток по часу 0–23: утро 5–11, день 12–17, вечер 18–22, ночь 23–4. */
export function partOfDay(hour) {
  const h = Number(hour);
  if (!Number.isInteger(h) || h < 0 || h > 23) return 'day';
  if (h >= 5 && h <= 11) return 'morning';
  if (h >= 12 && h <= 17) return 'day';
  if (h >= 18 && h <= 22) return 'evening';
  return 'night';
}

/** «день / дня / дней» для числа. */
export function pluralDays(n) {
  return plural(n, 'день', 'дня', 'дней');
}

/** «привычка / привычки / привычек» для числа. */
export function pluralHabits(n) {
  return plural(n, 'привычка', 'привычки', 'привычек');
}

function plural(n, one, few, many) {
  const abs = Math.abs(Math.trunc(Number(n) || 0));
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

