/** Индекс варианта из rand() ∈ [0, 1); неподходящее значение → крайние варианты. */
function pickIndex(rand, length) {
  const r = typeof rand === 'function' ? Number(rand()) : 0;
  if (!Number.isFinite(r) || r <= 0) return 0;
  return Math.min(length - 1, Math.floor(r * length));
}

function count(value) {
  const n = Math.trunc(Number(value));
  return Number.isFinite(n) && n >= 0 ? n : 0;
}

/**
 * Реплика персонажа на повод с подстановками.
 * ctx: { name, habit, streak, left, done, total, hour | part }.
 * rand — функция случайности (в браузере Math.random, в тестах — детерминированная).
 * Неизвестный повод → пустая строка; неизвестный персонаж → кот.
 */
export function pickPhrase(event, ctx = {}, characterId = DEFAULT_CHARACTER, rand = Math.random) {
  const character = getCharacter(characterId);
  const variants = PHRASES[character.id][event];
  if (!Array.isArray(variants) || variants.length === 0) return '';
  const template = variants[pickIndex(rand, variants.length)];

  const part = ['morning', 'day', 'evening', 'night'].includes(ctx.part) ? ctx.part : partOfDay(ctx.hour);
  const streak = count(ctx.streak);
  const left = count(ctx.left);
  const values = {
    name: normalizeCompanionName(ctx.name) ?? character.defaultName,
    habit: typeof ctx.habit === 'string' && ctx.habit !== '' ? ctx.habit : 'привычка',
    streak: `${streak} ${pluralDays(streak)}`,
    left: `${left} ${pluralHabits(left)}`,
    done: String(count(ctx.done)),
    total: String(count(ctx.total)),
    hello: HELLO[character.id][part],
  };
  // Один проход по шаблону: подставленный текст (например, название привычки с «{…}»)
  // повторно не разбирается.
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? values[key] : match));
}


/** Был ли до дня today хотя бы один день, когда выполнены все привычки дня. */
function hadClosedDayBefore(state, today) {
  const keys = new Set();
  for (const habit of state.habits) {
    for (const key of habit.done) if (key < today) keys.add(key);
  }
  for (const key of keys) {
    const { done, total } = getTodaySummary(state, key);
    if (total > 0 && done === total) return true;
  }
  return false;
}

/**
 * Повод реплики после переключения отметки дня date (по умолчанию — сегодня).
 * before/after — состояние привычек до и после, today — 'YYYY-MM-DD'.
 * habitId — какая привычка переключена (если не указан — первая, у которой
 * изменилась отметка дня date).
 * Возвращает null, если отметка не изменилась, иначе
 * { event, ctx: { habit, streak, left, done, total } }, где event (по приоритету):
 *  - 'unmark' — отметку сняли (любой день);
 *  - 'milestone' — серия стала вехой STREAK_MILESTONES (3, 7, 14, 30, 50, 100);
 *  - 'newRecord' — серия ≥ 2 и стала новой лучшей серией привычки;
 *  - 'markPast' — отмечен прошлый день (дальше — только для сегодняшнего дня);
 *  - 'firstDayClosed' — выполнены все привычки дня, и раньше такого дня не было;
 *  - 'allDone' — выполнены все привычки дня;
 *  - 'remaining' — до закрытия дня осталось 1–2 привычки;
 *  - 'markStreak' — серия ≥ 2;
 *  - 'mark' — иначе.
 */
export function companionEventForMark({ before, after, today, habitId, date = today } = {}) {
  const beforeHabits = Array.isArray(before?.habits) ? before.habits : [];
  const afterHabits = Array.isArray(after?.habits) ? after.habits : [];

  const changed = (habit) => {
    const prev = beforeHabits.find((h) => h.id === habit.id);
    return Boolean(prev) && isDone(prev, date) !== isDone(habit, date);
  };
  const habit =
    habitId !== undefined
      ? afterHabits.find((h) => h.id === habitId && changed(h))
      : afterHabits.find(changed);
  if (!habit) return null;
  const prev = beforeHabits.find((h) => h.id === habit.id);

  const { done, total } = getTodaySummary(after, today);
  const streak = getStreak(habit, today);
  const left = Math.max(0, total - done);
  const ctx = { habit: habit.name, streak, left, done, total };

  if (!isDone(habit, date)) return { event: 'unmark', ctx };
  if (STREAK_MILESTONES.includes(streak) && streak > getStreak(prev, today)) return { event: 'milestone', ctx };
  if (streak >= 2 && streak === getBestStreak(habit) && getBestStreak(habit) > getBestStreak(prev)) {
    return { event: 'newRecord', ctx };
  }
  if (date !== today) return { event: 'markPast', ctx };
  if (total > 0 && done === total) {
    const firstEver = !hadClosedDayBefore(after, today);
    return { event: firstEver ? 'firstDayClosed' : 'allDone', ctx };
  }
  if (left >= 1 && left <= 2) return { event: 'remaining', ctx };
  if (streak >= 2) return { event: 'markStreak', ctx };
  return { event: 'mark', ctx };
}

/** Повод после добавления привычки: первая в списке → 'firstHabit', иначе 'added'. */
export function companionEventForAdd({ before, after } = {}) {
  const beforeHabits = Array.isArray(before?.habits) ? before.habits : [];
  const afterHabits = Array.isArray(after?.habits) ? after.habits : [];
  const added = afterHabits.find((h) => !beforeHabits.some((b) => b.id === h.id));
  if (!added) return null;
  return { event: beforeHabits.length === 0 ? 'firstHabit' : 'added', ctx: { habit: added.name } };
}
