// Номер дня от 1970-01-01 для локальной даты 'YYYY-MM-DD' (без часовых поясов).
function dayNumber(dateKey) {
  const [y, m, d] = dateKey.split('-').map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
}

/** Совет для даты: детерминированно, следующий день — следующий совет по кругу. */
export function tipForDay(dateKey) {
  if (!isDateKey(dateKey)) return TIPS[0];
  const n = dayNumber(dateKey) % TIPS.length;
  return TIPS[(n + TIPS.length) % TIPS.length];
}

/**
 * Показывать ли совет дня: помощник включён и знакомство пройдено,
 * а сегодня (локальная дата todayKey) совета ещё не было.
 */
export function shouldShowTip(settings, todayKey) {
  if (!settings || typeof settings !== 'object') return false;
  if (!isDateKey(todayKey)) return false;
  if (settings.enabled === false || settings.introduced !== true) return false;
  return settings.lastTipDate !== todayKey;
}
