/**
 * Приводит вопрос к виду для сравнения: нижний регистр, ё → е,
 * знаки препинания и прочие символы → пробел, лишние пробелы убраны.
 */
export function normalizeQuestion(text) {
  if (typeof text !== 'string') return '';
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim();
}

