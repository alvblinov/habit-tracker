/** Кнопки частых вопросов: id записи и текст на кнопке. */
export const QUICK_QUESTIONS = QA.filter((entry) => entry.quick).map((entry) => ({
  id: entry.id,
  label: entry.quick,
}));

// Ключи записей, разбитые на слова.
const KEYWORDS = QA.map((entry) =>
  entry.keywords.map((key) => normalizeQuestion(key).split(' ').filter(Boolean)).filter((words) => words.length > 0),
);

// Слова вопроса words[i…] начинаются с частей ключа подряд.
function matchesAt(words, i, keyWords) {
  return keyWords.every((part, j) => i + j < words.length && words[i + j].startsWith(part));
}

function matches(words, keyWords) {
  for (let i = 0; i < words.length; i += 1) if (matchesAt(words, i, keyWords)) return true;
  return false;
}

/**
 * Запись с лучшим совпадением ключевых слов или null.
 * Счёт — число совпавших ключей; при равенстве — длиннее совпадение, затем порядок в QA.
 */
export function findAnswer(text) {
  const question = normalizeQuestion(text);
  if (question === '') return null;
  const words = question.split(' ');
  let best = null;
  let bestScore = 0;
  let bestLength = 0;
  QA.forEach((entry, index) => {
    let score = 0;
    let length = 0;
    for (const keyWords of KEYWORDS[index]) {
      if (matches(words, keyWords)) {
        score += 1;
        length += keyWords.join(' ').length;
      }
    }
    if (score > bestScore || (score === bestScore && score > 0 && length > bestLength)) {
      best = entry;
      bestScore = score;
      bestLength = length;
    }
  });
  return best;
}

/** Запись по id (для кнопок частых вопросов) или null. */
export function getAnswerEntry(id) {
  return QA.find((entry) => entry.id === id) ?? null;
}

