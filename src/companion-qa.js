/** Текст ответа записи в стиле персонажа. */
export function answerText(entry, characterId) {
  const character = getCharacter(characterId);
  const leads = LEADS[character.id];
  const index = Math.max(0, QA.indexOf(entry));
  return `${leads[index % leads.length]} ${entry.answer}`;
}

/** Ответ на незнакомый вопрос в стиле персонажа. */
export function unknownAnswer(characterId) {
  return UNKNOWN[getCharacter(characterId).id];
}

/** Ответ на вопрос: { id, text }; id — запись QA или 'unknown'. */
export function answerQuestion(text, characterId) {
  const entry = findAnswer(text);
  if (!entry) return { id: 'unknown', text: unknownAnswer(characterId) };
  return { id: entry.id, text: answerText(entry, characterId) };
}
